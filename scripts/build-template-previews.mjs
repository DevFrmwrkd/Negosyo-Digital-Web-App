/**
 * `.dc.html` design files. `letter` is the preview filename; `page` is the
 * data-page value of the wrapper this design was ported into, stamped onto the
 * preview's <html> so the two can never be confused for one another.
 *
 * The four foodcraft templates before BP (BL, BM, BN, BO) are deliberately NOT
 * listed. Their previews are already committed and already correct, and
 * re-generating them through this path would rewrite four shipped files for no
 * gain. Add a design here when you port it, not retroactively.
 */
