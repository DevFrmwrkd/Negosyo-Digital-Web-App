/* ────────────────────────────────────────────────────────────────────────────
 * THE .dc.html RENDERER
 * ──────────────────────────────────────────────────────────────────────────── */

/** Resolve a dotted path ("g.items", "t.n") against a scope object. */
function resolvePath(scope, expr) {
    return String(expr).trim().split('.').reduce(
        (acc, key) => (acc === null || acc === undefined ? undefined : acc[key]),
        scope,
    );
}

/**
 * Fill `{{ path }}` holes. Values are inserted RAW, exactly as the design's own
 * renderer inserts them: several props (btnBrown, btnNav, btnCream) are whole
 * CSS declaration lists destined for a style attribute, and escaping them would
 * print the CSS instead of applying it. A missing path resolves to '' rather
 * than the literal "undefined".
 */
function fillHoles(html, scope) {
    return html.replace(/\{\{\s*([^{}]+?)\s*\}\}/g, (_m, expr) => {
        const v = resolvePath(scope, expr);
        return v === null || v === undefined ? '' : String(v);
    });
}

/**
 * Expand `<sc-for list="{{ path }}" as="name">…</sc-for>`, innermost loops
 * included — the menu nests one inside another. The matching close tag is found
 * by counting opens and closes rather than by a lazy regex, which would stop at
 * the first `</sc-for>` and swallow the outer loop's tail.
 */
function expandLoops(html, scope) {
    const open = /<sc-for\b([^>]*)>/i.exec(html);
    if (!open) return fillHoles(html, scope);

    const bodyStart = open.index + open[0].length;
    const tok = /<sc-for\b[^>]*>|<\/sc-for>/gi;
    tok.lastIndex = bodyStart;
    let depth = 1;
    let bodyEnd = -1;
    let afterStart = -1;
    let t;
    while ((t = tok.exec(html)) !== null) {
        if (t[0].toLowerCase().startsWith('</')) {
            depth -= 1;
            if (depth === 0) { bodyEnd = t.index; afterStart = t.index + t[0].length; break; }
        } else {
            depth += 1;
        }
    }
    if (bodyEnd === -1) throw new Error('unclosed <sc-for> in design source');

    const attrs = open[1];
    const listExpr = /list="\{\{\s*([^}]+?)\s*\}\}"/i.exec(attrs);
    const asName = /\bas="([^"]+)"/i.exec(attrs);
    const list = listExpr ? resolvePath(scope, listExpr[1]) : [];

    const body = html.slice(bodyStart, bodyEnd);
    let out = '';
    if (Array.isArray(list)) {
        for (const item of list) {
            out += expandLoops(body, { ...scope, [asName ? asName[1] : 'it']: item });
        }
    }
    // `before` cannot contain a loop — this was the FIRST one — so it only needs
    // its holes filled. `after` may contain more, so it recurses.
    return fillHoles(html.slice(0, open.index), scope) + out + expandLoops(html.slice(afterStart), scope);
}

/**
 * Turn a design file into a standalone preview page.
 *
 * The design's own default props drive it: data-props carries an
 * HTML-entity-encoded JSON map of { editor, default, … } per prop, and
 * renderVals() turns those into the values the markup reads. Evaluating the
 * design's class is the whole point — a preview built from retyped values is a
 * preview that can lie about the template it advertises.
 */
function renderDc(source, { label, page }) {
    // 1 · the props the design ships as its defaults.
    const propsAttr = /data-props="([^"]*)"/i.exec(source);
    const propsJson = propsAttr
        ? propsAttr[1].replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
        : '{}';
    const propSpecs = JSON.parse(propsJson);
    const props = Object.fromEntries(
        Object.entries(propSpecs).map(([k, spec]) => [k, spec && typeof spec === 'object' ? spec.default : undefined]),
    );

    // 2 · the design's own logic, run against them.
    const classSrc = /<script[^>]*data-dc-script[^>]*>([\s\S]*?)<\/script>/i.exec(source);
    if (!classSrc) throw new Error('no data-dc-script block found');
    // eslint-disable-next-line no-new-func
    const makeComponent = new Function(
        'props',
        `class DCLogic { constructor(p) { this.props = p; } }\n${classSrc[1]}\nreturn new Component(props);`,
    );
    const vals = makeComponent(props).renderVals();

    // 3 · the markup, minus the authoring-time wrapper elements.
    const bodyMatch = /<x-dc>([\s\S]*?)<\/x-dc>/i.exec(source);
    if (!bodyMatch) throw new Error('no <x-dc> block found');
    let body = bodyMatch[1];
    const helmet = /<helmet>([\s\S]*?)<\/helmet>/i.exec(body);
    const head = helmet
        ? helmet[1].replace(/<script\s+src=["']\.?\/?image-slot\.js["'][^>]*><\/script>\s*/gi, '')
        : '';
    body = body.replace(/<helmet>[\s\S]*?<\/helmet>/i, '');

    // 4 · loops, then holes.
    body = expandLoops(body, vals);

    // 5 · the image slots. Unlike sanitize(), which paints its own slate
    //     gradient, these become a TRANSPARENT label: every plate in a design
    //     file already has its own background on the PARENT element, and
    //     covering it would replace the design's colour with one this script
    //     invented.
    body = body.replace(/<image-slot\b([^>]*)>\s*<\/image-slot>/gi, (_m, attrs) => {
        const ph = /placeholder=["']([^"']*)["']/i.exec(attrs);
        return (
            '<div style="position:absolute;inset:0;display:flex;align-items:center;justify-content:center;' +
            'font-family:ui-monospace,monospace;font-size:10px;letter-spacing:.14em;text-transform:uppercase;' +
            'opacity:.42;padding:10px;text-align:center;">' + (ph ? ph[1] : 'Image') + '</div>'
        );
    });

    return `<!DOCTYPE html>
<!--
  GENERATED from "${path.basename(label)}" by scripts/build-template-previews.mjs,
  which EVALUATES the design's own renderVals() and expands its own sc-for
  loops. No demo value here was retyped, so this preview cannot drift from the
  design it advertises. Re-run the script rather than editing by hand.
-->
<html lang="en-PH" data-page="${page}">
<head>
  <!-- preview: ${label} (autogenerated from the design) -->
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Preview</title>
${head.trim()}
</head>
<body>
${body.trim()}
</body>
</html>
`;
}

function sanitize(html, label) {
    let out = html;

    // 1. Remove the script tag that loads image-slot.js.
    out = out.replace(/<script\s+src=["']image-slot\.js["'][^>]*><\/script>\s*/gi, '');

    // 2. Replace <image-slot …></image-slot> with a placeholder div that
    //    fills its parent's slot. We preserve the placeholder text so the
    //    admin can still see what was meant to go there.
    out = out.replace(
        /<image-slot\b([^>]*)>\s*<\/image-slot>/gi,
        (_match, attrs) => {
            const phMatch = /placeholder=["']([^"']+)["']/i.exec(attrs);
            const placeholder = phMatch ? phMatch[1] : 'Image';
            return (
                '<div style="width:100%;height:100%;display:flex;align-items:center;justify-content:center;' +
                'background:linear-gradient(135deg,#e2e8f0,#cbd5e1);color:#475569;font-family:ui-monospace,monospace;' +
                'font-size:11px;letter-spacing:.06em;text-transform:uppercase;padding:8px;text-align:center;">' +
                placeholder +
                '</div>'
            );
        },
    );

    // 3. Strip the floating switcher nav.
    out = out.replace(/<nav\s+class=["']switcher["'][\s\S]*?<\/nav>/i, '');

    // 4. Drop the floating CTA so previews aren't littered with absolute UI.
    out = out.replace(/<div\s+class=["']float-cta["'][\s\S]*?<\/div>\s*<\/div>/i, '');

    // 5. Mark the document as a preview so we never accidentally serve it
    //    as a real submission. (Comment only — no behaviour change.)
    out = out.replace('<head>', `<head>\n  <!-- preview: ${label} (autogenerated) -->`);

    return out;
}

async function main() {
    await fs.mkdir(OUT_DIR, { recursive: true });
    let total = 0;
    for (const tpl of TEMPLATES) {
        const src = path.join(tpl.dir, tpl.file);
        const dest = path.join(OUT_DIR, `${tpl.letter}.html`);
        try {
            const html = await fs.readFile(src, 'utf-8');
            const sanitized = sanitize(html, tpl.label);
            await fs.writeFile(dest, sanitized, 'utf-8');
            console.log(`  ✓ ${tpl.letter}.html  (${tpl.label})  ${(sanitized.length / 1024).toFixed(1)} KB`);
            total++;
        } catch (err) {
            console.error(`  ✗ ${tpl.letter}.html — ${err.message}`);
        }
    }
    for (const tpl of DC_TEMPLATES) {
        const src = path.join(tpl.dir, tpl.file);
        const dest = path.join(OUT_DIR, `${tpl.letter}.html`);
        try {
            const html = await fs.readFile(src, 'utf-8');
            const rendered = renderDc(html, tpl);
            await fs.writeFile(dest, rendered, 'utf-8');
            console.log(`  ✓ ${tpl.letter}.html  (${tpl.label})  ${(rendered.length / 1024).toFixed(1)} KB  [from design]`);
            total++;
        } catch (err) {
            console.error(`  ✗ ${tpl.letter}.html — ${err.message}`);
        }
    }

    const expected = TEMPLATES.length + DC_TEMPLATES.length;
    console.log(`\nWrote ${total}/${expected} previews to ${path.relative(ROOT, OUT_DIR)}/`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
